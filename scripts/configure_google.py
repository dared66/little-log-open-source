#!/usr/bin/env python3
"""Select public production IDs or validate local IDs, then generate iOS settings."""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CLIENT_KEYS = ('GOOGLE_WEB_CLIENT_ID', 'GOOGLE_IOS_CLIENT_ID')


def validate_config(config):
    if not isinstance(config, dict):
        raise ValueError('Google configuration must be a JSON object.')
    for name in CLIENT_KEYS:
        value = config.get(name, '')
        if not isinstance(value, str) or (value and not re.fullmatch(
                r'[0-9]+-[A-Za-z0-9-]+\.apps\.googleusercontent\.com', value)):
            raise ValueError(f'{name} must be an OAuth client ID, not a secret or token.')
    number = config.get('GOOGLE_PROJECT_NUMBER', '')
    if not isinstance(number, str) or (number and not number.isdigit()):
        raise ValueError('GOOGLE_PROJECT_NUMBER must be a numeric string.')
    projects = {config[name].split('-', 1)[0] for name in CLIENT_KEYS if config.get(name)}
    if number:
        projects.add(number)
    if len(projects) > 1:
        raise ValueError('Google client IDs and project number must belong to the same project.')
    if config.get('GOOGLE_CLOUD_PROJECT_ID') == 'little-log-production-509904':
        raise ValueError('The retired Google project must not be used for Little Log releases.')
    if config.get('GOOGLE_CLOUD_PROJECT_ID') == 'little-log-509004':
        expected = json.loads((ROOT / 'config/google.production.json').read_text())
        for name in (*CLIENT_KEYS, 'GOOGLE_PROJECT_NUMBER'):
            if config.get(name) != expected[name]:
                raise ValueError(f'{name} does not match the verified production configuration.')


def configure(root=ROOT, *, production=False):
    config_path = root / 'config/google.local.json'
    if production:
        config = json.loads((root / 'config/google.production.json').read_text())
        validate_config(config)
        if config_path.exists():
            previous = json.loads(config_path.read_text())
            validate_config(previous)
            if previous.get('GOOGLE_PROJECT_NUMBER') != config['GOOGLE_PROJECT_NUMBER']:
                backup = root / 'config/google.testing.local.json'
                if backup.exists() and backup.read_bytes() != config_path.read_bytes():
                    raise ValueError('A different testing backup already exists; refusing to overwrite it.')
                backup.write_bytes(config_path.read_bytes())
                print('Preserved testing configuration in config/google.testing.local.json.')
            else:
                config['GOOGLE_PICKER_API_KEY'] = previous.get('GOOGLE_PICKER_API_KEY', '')
            config['PLAY_BILLING_PUBLIC_KEY'] = previous.get('PLAY_BILLING_PUBLIC_KEY', '')
        config_path.write_text(json.dumps(config, indent=2) + '\n')
    else:
        if not config_path.exists():
            raise ValueError('Create config/google.local.json or run this script with --production.')
        config = json.loads(config_path.read_text())
        validate_config(config)
    ios = config.get('GOOGLE_IOS_CLIENT_ID', '')
    reversed_id = '.'.join(reversed(ios.split('.'))) if ios else ''
    (root / 'ios/Flutter/GoogleConfig.xcconfig').write_text(
        '// Generated by scripts/configure_google.py; do not commit.\n'
        f'GOOGLE_IOS_REVERSED_CLIENT_ID={reversed_id}\n')
    print('Generated the local iOS Google callback setting.' if ios else
          'Generated an empty callback; Google sign-in remains disabled.')
    print('Build with --dart-define-from-file=config/google.local.json.')
    return config


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--production', action='store_true',
                        help='Select verified Little Log production IDs; preserve the testing config.')
    args = parser.parse_args()
    try:
        configure(production=args.production)
    except (ValueError, OSError) as exc:
        parser.exit(1, f'Google configuration failed: {exc}\n')


if __name__ == '__main__':
    main()
